#!/usr/bin/env python3
"""Generates src/tables.rs: the sRGB decode table L(v) and the encode thresholds T[v].

Exact decimal arithmetic, no floating point, so the output does not depend on
the machine. See docs/mid-ui-contracts.md section 1.3 for the rules the tables
follow and docs/mid-raster.md section "tables.rs".

    python3 tools/gen_linear_tables.py > src/tables.rs
"""
import hashlib
import struct
from decimal import ROUND_HALF_UP, Decimal as D, getcontext

getcontext().prec = 60


def eotf(v):
    c = D(v) / D(255)
    if c <= D("0.04045"):
        return c / D("12.92")
    return ((c + D("0.055")) / D("1.055")) ** D("2.4")


L = [int((eotf(v) * 65535).to_integral_value(rounding=ROUND_HALF_UP)) for v in range(256)]
assert L[0] == 0 and L[255] == 65535
assert all(L[i] < L[i + 1] for i in range(255)), "decode must be strictly increasing"
T = [(L[v] + L[v + 1]) // 2 for v in range(255)]


def encode(l):
    lo, hi = 0, 255
    while lo < hi:
        mid = (lo + hi) // 2
        if l > T[mid]:
            lo = mid + 1
        else:
            hi = mid
    return lo


assert all(encode(L[v]) == v for v in range(256)), "round trip"


def fnv1a(data):
    h = 0xCBF29CE484222325
    for b in data:
        h = ((h ^ b) * 0x100000001B3) & 0xFFFFFFFFFFFFFFFF
    return h


db = struct.pack("<256H", *L)
tb = struct.pack("<255H", *T)


def rows(vals, per=12):
    out = []
    for i in range(0, len(vals), per):
        out.append("    " + ", ".join(str(x) for x in vals[i : i + per]) + ",")
    return "\n".join(out)


print(f'''// ============================================================================
// NOTICE: Full documentation, design decisions, and fix history for this file
// live in docs/mid-raster.md, section "tables.rs"
// ============================================================================
//! Generated by `tools/gen_linear_tables.py`. Do not edit by hand.
//!
//! SHA-256 of the decode table as 256 little-endian `u16`:
//! `{hashlib.sha256(db).hexdigest()}`
//! SHA-256 of the thresholds as 255 little-endian `u16`:
//! `{hashlib.sha256(tb).hexdigest()}`

/// sRGB level to linear light scaled to 0..=65535, rounded half up.
pub const DECODE: [u16; 256] = [
{rows(L)}
];

/// Midpoints between neighboring decoded levels, `(DECODE[v] + DECODE[v + 1]) / 2`.
pub const THRESHOLDS: [u16; 255] = [
{rows(T)}
];

/// FNV-1a 64 of `DECODE` as little-endian bytes, checked by a test.
pub const DECODE_FNV: u64 = {fnv1a(db):#018x};

/// FNV-1a 64 of `THRESHOLDS` as little-endian bytes, checked by a test.
pub const THRESHOLDS_FNV: u64 = {fnv1a(tb):#018x};''')
